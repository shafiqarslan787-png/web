export const pick = <T,>(arr: T[], avoid?: T): T => {
  const a = arr as T[];
  if (a.length < 2) return a[0] as T;
  let v = a[Math.floor(Math.random() * a.length)] as T;
  while (v === avoid) v = a[Math.floor(Math.random() * a.length)] as T;
  return v;
};
